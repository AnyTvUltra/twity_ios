def unescape_dart(s):
    """Turn raw literal body (\\n, $, \\', \\\\, \\t) into the evaluated string
    — the runtime key produced when Dart parses '...'."""
    out = []
    i = 0
    while i < len(s):
        if s[i] == '\\' and i + 1 < len(s):
            c = s[i + 1]
            out.append({'n': '\n', 't': '\t', 'r': '\r', '\\': '\\',
                        "'": "'", '"': '"', '$': '$', '0': '\0'}.get(c, c))
            i += 2
        else:
            out.append(s[i])
            i += 1
    return ''.join(out)

def dq(s):
    s = (s.replace('\\', '\\\\').replace("'", "\\'")
          .replace('\n', '\\n').replace('\t', '\\t').replace('\r', '\\r'))
    # كل $ حرفية (لا يوجد ${} حقيقي — القوالب تستخدم {})
    s = s.replace('$', '\\$')
    return "'" + s + "'"

